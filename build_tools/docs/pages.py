"""Render every generated documentation page and write it into docs/.

Pages from repository files always render. Pages from external data render
from what the environment provides and otherwise say the data was absent, so a
local or offline build still succeeds:

- ``FASTFLOW_SDK_DOCS_RELEASE``: the release tag the site documents. The
  release pages start from it and the versions page names it; else ``main``.
- ``FASTFLOW_SDK_DOCS_RELEASES``: releases API JSON, as fetched for the index.
- ``FASTFLOW_SDK_DOCS_MODEL_LIST``: FastFlowLM ``model_list.json``; defaults to
  the ``projects/FastFlowLM`` checkout.
- ``FASTFLOW_SDK_DOCS_IRON_ROOT``: an IRON source tree; defaults to the
  ``projects/iron-ops`` checkout.
"""

from __future__ import annotations

import json
import shutil
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

from build_tools.docs import catalogs, cli, releases, versions

DOCS = Path("docs")
MODEL_LIST = Path("projects") / "FastFlowLM" / "src" / "model_list.json"
IRON_ROOT = Path("projects") / "iron-ops"
# Scripts the pages show, published at the same path under the site so a
# reader can download the documented release's copy.
EXAMPLES = ("examples/hello_npu.py", "examples/serve/*.py")


@dataclass(frozen=True)
class Inputs:
    root: Path
    release: str | None = None
    releases: Path | None = None
    model_list: Path | None = None
    iron_root: Path | None = None


@dataclass(frozen=True)
class Page:
    text: str
    # The repository file to edit to change the page: its data, or for
    # external data, the generator.
    source: str


def inputs_from_environment(root: Path, environ: Mapping[str, str]) -> Inputs:
    def path(variable: str, default: Path | None = None) -> Path | None:
        if environ.get(variable):
            return Path(environ[variable])
        return default

    model_list = root / MODEL_LIST
    iron_root = root / IRON_ROOT
    return Inputs(
        root=root,
        release=environ.get("FASTFLOW_SDK_DOCS_RELEASE") or None,
        releases=path("FASTFLOW_SDK_DOCS_RELEASES"),
        model_list=path(
            "FASTFLOW_SDK_DOCS_MODEL_LIST", model_list if model_list.is_file() else None
        ),
        iron_root=path(
            "FASTFLOW_SDK_DOCS_IRON_ROOT",
            iron_root if (iron_root / "iron" / "operators").is_dir() else None,
        ),
    )


def generate(inputs: Inputs) -> dict[str, Page]:
    root = inputs.root
    command_source = (root / cli.COMMAND_SOURCE).read_text(encoding="utf-8")
    checks = cli.load_checks(root / cli.CHECKS)
    pins, release_policy = versions.load(root)
    published = (
        releases.load_releases(inputs.releases, inputs.release)
        if inputs.releases
        else None
    )
    model_list = (
        json.loads(inputs.model_list.read_text(encoding="utf-8"))
        if inputs.model_list
        else None
    )
    return {
        "reference/cli.md": Page(
            cli.cli_page(command_source, checks), cli.COMMAND_SOURCE.as_posix()
        ),
        "reference/troubleshooting.md": Page(
            cli.troubleshooting_page(checks), cli.CHECKS.as_posix()
        ),
        "reference/models.md": Page(
            catalogs.models_page(
                model_list, versions.pinned_commit(pins, "fastflowlm")
            ),
            _module_path(catalogs),
        ),
        "reference/operators.md": Page(
            catalogs.operators_page(
                inputs.iron_root, versions.pinned_commit(pins, "iron_ops")
            ),
            _module_path(catalogs),
        ),
        "reference/hardware.md": Page(
            releases.hardware_page(published), _module_path(releases)
        ),
        "reference/versions.md": Page(
            versions.versions_page(pins, release_policy, inputs.release or "main"),
            versions.VERSIONS.as_posix(),
        ),
        "releases.md": Page(releases.releases_page(published), _module_path(releases)),
    }


def examples(root: Path) -> list[str]:
    return sorted(
        path.relative_to(root).as_posix()
        for pattern in EXAMPLES
        for path in root.glob(pattern)
    )


def write(inputs: Inputs) -> list[Path]:
    """Write the generated pages and example copies into docs/; return them."""
    docs = inputs.root / DOCS
    written = []
    for name, page in generate(inputs).items():
        target = docs / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            f"<!-- Generated by build_tools/docs from {page.source}. -->\n\n"
            + page.text,
            encoding="utf-8",
            newline="\n",
        )
        written.append(target)
    for name in examples(inputs.root):
        target = docs / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(inputs.root / name, target)
        written.append(target)
    return written


def _module_path(module) -> str:
    return Path(module.__file__).relative_to(Path(__file__).parents[2]).as_posix()
